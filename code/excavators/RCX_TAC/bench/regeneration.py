def other_partition(physical):
    return next(k for k in physical['partition_requests'] if k != 'joint_space')


def build(machine, physical, change, partition, sample_time=0.01, repeats=3):
    """Compiled interfaces of one variant; the compile time is the smallest of ``repeats`` calls (other jobs may share
    the processor)."""
    study = machine.regeneration_study(physical)
    spec = machine.spec(physical, sample_time=sample_time, joint_limits=study['joint_limits'])
    if change is not None:
        spec = change(spec)
    best = np.inf
    for _ in range(repeats):
        t0 = time.perf_counter()
        xc = compile_extended(physical, spec, partition)
        best = min(best, time.perf_counter() - t0)
    pin_id = study['info'].get('pin')
    xc.study = dict(targets=study['targets'], mid=study['mid'], **study['info'], pin_is_cut=bool(pin_id in xc.ci.cut_ids))
    return xc, best


# ---------------------------------------------------------------------------------------------- Pinocchio model on contacts
class GroundedPinModel(PinModel):
    """Pinocchio model of a graph that stands on declared ground contacts: the frame of every contact anchor is pinned to
    the root frame at its seed position by a point constraint of Pinocchio (CONTACT_3D), next to the constraints of the
    cut joints.  The multipliers of these constraints are the forces of the ground on the mechanism."""

    def __init__(self, cmg, cut_ids, held_points, **kw):
        super().__init__(cmg, cut_ids, **kw)
        self.n_closure = len(self.constraints)
        self.held_names = []
        for name, (body, world) in held_points.items():
            placement = self.placement[body]
            cm = pin.RigidConstraintModel(pin.ContactType.CONTACT_3D, self.model, self.support[body], pin.SE3(np.eye(3), placement[:3, 3].copy()),
                                          0, pin.SE3(np.eye(3), np.asarray(world, float).copy()), pin.ReferenceFrame.LOCAL_WORLD_ALIGNED)
            cm.name = 'held_' + name
            self.constraints.append(cm)
            self.held_names.append(name)
        self.constraint_datas = [c.createData() for c in self.constraints]
        pin.initConstraintDynamics(self.model, self.data, self.constraints)

    def contact_forces(self):
        """Forces of the ground on the contacts (n, 3) from the last call of ``constrained_acceleration``."""
        return np.array(self.data.lambda_c)[3 * self.n_closure:].reshape(-1, 3).copy()


def pin_model(physical, xc, **kw):
    """Pinocchio model of the compiled tree and cut set of ``xc`` (with pinned contact anchors if it has a support)."""
    ci = xc.ci
    if xc.support is None:
        return PinModel(ci.comp.cmg, ci.cut_ids, gravity=physical['gravity_m_s2'], **kw)
    held = {c['id']: (c['frame'], [float(physical['seed']['joints'][a]) for a in c['anchor']]) for c in xc.support.contacts}
    return GroundedPinModel(ci.comp.cmg, ci.cut_ids, held, gravity=physical['gravity_m_s2'], **kw)


def test_box(machine, physical, planner):
    """(lower, upper, narrow) of the task coordinates for random test states: declared windows, -1.2 .. 1.2 for coordinates
    without a window, and the ranges that the adapter declares for the offline tests (``narrow``: those coordinates)."""
    lo, hi, _ = planner.task_box()
    lo, hi = np.where(np.isfinite(lo), lo, -1.2), np.where(np.isfinite(hi), hi, 1.2)
    narrow = np.zeros(len(lo), bool)
    for jid, (a, b) in machine.test_ranges(physical).items():
        if jid in planner.task_ids:
            lo[planner.index(jid)], hi[planner.index(jid)], narrow[planner.index(jid)] = a, b, True
    return lo, hi, narrow


# ---------------------------------------------------------------------------------------------- offline audits
def expm_so3(w):
    th = np.linalg.norm(w)
    K = np.array([[0, -w[2], w[1]], [w[2], 0, -w[0]], [-w[1], w[0], 0]])
    return np.eye(3) + (np.sin(th) / th * K + (1 - np.cos(th)) / th ** 2 * K @ K if th > 1e-12 else K)


def audit(physical, xc, xc_other, box, rng, samples=5, moving_root=True):
    """Offline checks of one regenerated interface (xc: joint space, xc_other: the other partition of the same records);
    ``box`` = (lower, upper, narrow) of the task coordinates from which the random states are drawn (``narrow``: the
    coordinates whose reference offsets are a tenth of the others).  ``moving_root``: the root frame of the graph is a
    body (random pose, twist and acceleration); otherwise it is the ground."""
    ci, plan = xc.ci, xc.plan
    joints = {j['id']: j for j in ci.comp.cmg['joints']}
    pm = pin_model(physical, xc)
    perm = np.array([ci.tree_ids.index(k) for k in pm.tree_ids])
    inv = np.argsort(perm)
    r = dict(closure=0., tangent=0., required_acceleration_closure=0., cut_point_velocity=0., cut_axis_rate=0., vdc_vs_reduced=0.,
             vdc_affine_map=0., storage_identity=0., dissipation_identity=0., reduced_inertia_rate_fd=0., skew_symmetry=0.,
             pinocchio_acceleration=0., barrier_hdot_fd=0., barrier_hddot_fd_p99=0., cut_limit_vs_lift=0., covariance_effort=0.,
             covariance_rows=0., covariance_row_coefficients=0., covariance_margins=0., covariance_storage=0.)
    if xc.support is not None:
        r.update(pinocchio_contact_force=0., distribution_constraint=0.)
    ctl_a, ctl_b = SafeVDC(xc, FilterOptions()), SafeVDC(xc_other, FilterOptions())
    ids_b = [ci.coordinate_ids.index(k) for k in xc_other.ci.independent_ids]
    lo, hi, narrow = box
    rates = lambda v: MachineTests.rates(v, xc)
    closed = lambda v, start=None: closed_configuration(ci, xc.compose(v), start=start)
    done = relaxed = 0
    while done < samples:
        u, ud = rng.uniform(lo, hi), rng.uniform(-0.3, 0.3, xc.d)
        try:
            q = closed(u)
        except ValueError:
            continue                                        # outside the assembly range of this variant
        lift = xc.lift(q, rates(ud))
        qt = q[ci.tree_rows]
        if moving_root:
            base = dict(p=rng.uniform(-1, 1, 3), R=expm_so3(rng.uniform(-0.15, 0.15, 3)), v=rng.uniform(-0.3, 0.3, 3), w=rng.uniform(-0.2, 0.2, 3))
            a_base = rng.uniform(-0.5, 0.5, 6)
        else:
            base = dict(p=np.zeros(3), R=np.eye(3), v=np.zeros(3), w=np.zeros(3))
            a_base = np.zeros(6)
        kin = plan.evaluate(qt, lift.vT, base['p'], base['R'], base['v'], base['w'])
        res, Jc, _ = ci.graph.residual(q)
        r['closure'] = max(r['closure'], float(np.max(np.abs(res))))
        r['tangent'] = max(r['tangent'], float(np.max(np.abs(Jc @ lift.E))))
        # loop consistency of an arbitrary required motion
        u_r, ur_dot = rng.uniform(-0.5, 0.5, xc.d), rng.uniform(-1, 1, xc.d)
        eps = 1e-6
        Jdot = (ci.graph.residual(q + eps * lift.v)[1] - ci.graph.residual(q - eps * lift.v)[1]) / (2 * eps)
        r['required_acceleration_closure'] = max(r['required_acceleration_closure'],
                                                 float(np.max(np.abs(Jc @ (lift.E @ ur_dot + lift.Edot @ u_r) + Jdot @ (lift.E @ u_r)))))
        nu_r = kin.nu.copy()
        nu_r[6:] = lift.ET @ u_r
        for jid in ci.cut_ids:
            j = joints[jid]
            A, B = plan.index[j['base_body']], plan.index[j['follower_body']]
            TA, TB = np.asarray(j['T_BJ']), np.asarray(j['T_FJ'])
            _, JA, _ = plan.point(kin, A, TA[:3, 3])
            _, JB, _ = plan.point(kin, B, TB[:3, 3])
            r['cut_point_velocity'] = max(r['cut_point_velocity'], float(np.max(np.abs((JA - JB) @ nu_r))))
            axis = kin.R[A] @ TA[:3, :3] @ np.asarray(j['axis'], float)
            r['cut_axis_rate'] = max(r['cut_axis_rate'], float(np.max(np.abs(np.cross((kin.J[A, 3:] - kin.J[B, 3:]) @ nu_r, axis)))))
        # VDC assembly against the reduced dynamics, storage identity
        Mr, hr, L, C, _ = xc.reduce(lift, kin, a_base)
        udd = rng.uniform(-1, 1, xc.d)
        mod = plan.vdc(kin, kin.nu, np.r_[a_base, lift.ET @ udd + lift.EdotT @ ud], 0.)
        r['vdc_vs_reduced'] = max(r['vdc_vs_reduced'], float(np.max(np.abs(lift.ET.T @ mod['tau'][6:] - (Mr @ udd + hr))) / np.max(np.abs(hr))))
        mod = plan.vdc(kin, nu_r, np.r_[a_base, lift.ET @ ur_dot + lift.EdotT @ u_r], xc.k_body)
        s = u_r - ud
        r['storage_identity'] = max(r['storage_identity'], abs(float(mod['storage'].sum()) - 0.5 * float(s @ Mr @ s)) / max(1., 0.5 * float(s @ Mr @ s)))
        # affine map of the VDC evaluator for a required motion different from the actual one, with gains
        ET, EdT = lift.ET, lift.EdotT
        Mqq, Mqb, Cqq, Cqb = kin.M[6:, 6:], kin.M[6:, :6], kin.C[6:, 6:], kin.C[6:, :6]
        Kr = ET.T @ plan.gain_matrix(kin, xc.k_body)[6:, 6:] @ ET
        Cr = ET.T @ (Mqq @ EdT + Cqq @ ET)
        c0 = ET.T @ (Mqb @ a_base + Cqb @ kin.nu[:6] + kin.grav[6:]) - Kr @ ud
        tau_affine = Mr @ ur_dot + (Cr + Kr) @ u_r + c0
        r['vdc_affine_map'] = max(r['vdc_affine_map'], float(np.max(np.abs(ET.T @ mod['tau'][6:] - tau_affine)) / np.max(np.abs(tau_affine))))
        r['dissipation_identity'] = max(r['dissipation_identity'], abs(float(mod['dissipation'].sum()) - float(s @ Kr @ s)) / max(1., float(s @ Kr @ s)))
        # rate of the reduced inertia: the generated M_r_dot against a centred difference of M_r along the motion, and the
        # skew-symmetry of  M_r_dot - 2 E_T^T (M Edot_T + C E_T)
        _, _, _, _, Mr_dot = xc.reduce(lift, kin, a_base)
        hfd = 1e-5

        def inertia(sign):
            q2 = closed(u + sign * hfd * ud, q)
            l2 = xc.lift(q2, rates(ud))
            k2 = plan.evaluate(q2[ci.tree_rows], l2.vT)
            return xc.reduce(l2, k2, np.zeros(6))[0]
        r['reduced_inertia_rate_fd'] = max(r['reduced_inertia_rate_fd'],
                                           float(np.max(np.abs(Mr_dot - (inertia(1.) - inertia(-1.)) / (2. * hfd))) / np.max(np.abs(Mr))))
        skew = Mr_dot - 2. * Cr
        r['skew_symmetry'] = max(r['skew_symmetry'], float(np.max(np.abs(skew + skew.T)) / np.max(np.abs(Mr))))
        # constrained accelerations against Pinocchio (fixed base)
        kin0 = plan.evaluate(qt, lift.vT)
        Mr0, hr0, L0, C0, _ = xc.reduce(lift, kin0, np.zeros(6))
        phi = rng.uniform(-1., 1., xc.m) * 0.2 * xc.scale
        if xc.support is not None:                           # around the efforts that hold the state (the machine stands on them)
            phi = MachineTests.holding_efforts(xc, lift, kin0, dict(a=np.zeros(6)), hr0, C0) + 0.25 * phi
        udd0 = np.linalg.solve(Mr0, C0 @ phi - hr0)
        a_tree = lift.ET @ udd0 + lift.cT
        tau_tree = xc.S_port @ (xc.G @ phi)
        a_pin = pm.constrained_acceleration(qt[perm], lift.vT[perm], tau_tree[perm])[inv]
        M0 = kin0.M[6:, 6:]
        r['pinocchio_acceleration'] = max(r['pinocchio_acceleration'],
                                          float(np.max(np.abs(M0 @ (a_tree - a_pin))) / max(1., np.max(np.abs(tau_tree)), np.max(np.abs(kin0.h[6:])))))
        if xc.support is not None:
            # contact forces of the generated map against the multipliers of Pinocchio's anchor constraints; the nominal
            # distribution reproduces the reduced effort
            sup = xc.support
            Mxf, hx, Cx = sup.held_maps(lift, kin0, np.zeros(6), xc.S_port, xc.G)
            A, b = sup.force_map(Mr0, hr0, C0, Mxf, hx, Cx, np.zeros(xc.d), np.zeros(len(xc.held)))
            r['pinocchio_contact_force'] = max(r['pinocchio_contact_force'],
                                               float(np.max(np.abs((A @ phi + b).reshape(-1, 3) - pm.contact_forces()))) / sup.weight)
            Dn, Dl = xc.nominal_map(C0, Cx)
            r['distribution_constraint'] = max(r['distribution_constraint'], float(np.max(np.abs(C0 @ Dn - np.eye(xc.d)))),
                                               float(np.max(np.abs(C0 @ Dl)) / max(1e-300, np.max(np.abs(Dl)))))
        # barrier rows by finite differences along the motion
        dt = 1e-5

        def at(sign):
            q2 = closed(u + sign * dt * ud, q)
            l2 = xc.lift(q2, rates(ud))
            k2 = plan.evaluate(q2[ci.tree_rows], l2.vT, base['p'] + sign * dt * base['v'], expm_so3(sign * dt * base['w']) @ base['R'], base['v'],
                               base['w'], dynamics=xc.support is not None)      # the support rows take their rates from the body modules
            return xc.barriers.evaluate(k2, q2[ci.tree_rows], broad_phase=False), k2
        rows = xc.barriers.evaluate(kin, qt, broad_phase=False)
        for j, (kind, data, sign, ref) in enumerate(xc.barriers.coord):       # rows of limits on cut joints against the lift
            if kind == 'cut':
                i, kc = xc.barriers.n_clearance + j, ci.coordinate_ids.index(data['joint'])
                r['cut_limit_vs_lift'] = max(r['cut_limit_vs_lift'], abs(rows.h[i] - (sign * q[kc] - ref)),
                                             float(np.max(np.abs(rows.G[i, 6:] @ lift.ET - sign * lift.E[kc]))),
                                             abs(rows.G[i, 6:] @ lift.cT + rows.beta[i] - sign * (lift.Edot[kc] @ ud)))
        (rp, kp), (rm, km) = at(1.), at(-1.)
        r['barrier_hdot_fd'] = max(r['barrier_hdot_fd'], float(np.max(np.abs(rows.G @ kin.nu - (rp.h - rm.h) / (2 * dt)))))
        hdd = rows.G[:, 6:] @ lift.cT + rows.beta
        err = np.abs(hdd - (rp.G @ kp.nu - rm.G @ km.nu) / (2 * dt)) / (1. + np.abs(hdd))
        r['barrier_hddot_fd_p99'] = max(r['barrier_hddot_fd_p99'], float(np.percentile(err, 99)))
        if xc.barriers.support is not None:                  # every support row (the percentile above could hide these few rows)
            k0 = xc.barriers.support['start']
            n_e = len(xc.barriers.support['edges'])
            r['support_hddot_fd'] = max(r.get('support_hddot_fd', 0.), float(np.max(err[k0:k0 + n_e])))
            r['support_hdot_fd'] = max(r.get('support_hdot_fd', 0.),
                                       float(np.max(np.abs(rows.G @ kin.nu - (rp.h - rm.h) / (2 * dt))[k0:k0 + n_e])))
        # covariance between the two partitions (one controller sample at the same physical state).  A random state can lie
        # beyond a declared limit; its required motion then comes from the relaxed shaping problem, whose stages carry a
        # tolerance of 1e-6: such a sample is counted in ``covariance_relaxed_samples`` and compared separately.
        ctl_a.reset()
        ctl_b.reset()
        cb = dict(position=base['p'], rotation=base['R'], velocity=np.r_[base['v'], base['w']], acceleration=a_base)
        f_meas = xc.G @ MachineTests.holding_efforts(xc, lift, kin, dict(a=a_base), hr, C)
        soft = np.where(narrow, 0.1, 1.)
        ref = (q[xc.task.rows] + rng.uniform(-0.05, 0.05, xc.d) * soft, rng.uniform(-0.05, 0.05, xc.d) * soft, np.zeros(xc.d))
        pa = ctl_a.step(0., q[ci.active], rates(ud), cb, f_meas, ref)
        pb = ctl_b.step(0., q[ids_b], lift.v[ids_b], cb, f_meas, ref)
        la, lb = ctl_a.last, ctl_b.last
        exact = la['velocity_level'] == 0 and la['feasible'] and lb['velocity_level'] == 0 and lb['feasible']
        eff = max(float(np.max(np.abs(pa - pb) / xc.scale)), float(np.max(np.abs(la['phi_r'] - lb['phi_r']) / xc.scale)))
        r['covariance_row_coefficients'] = max(r['covariance_row_coefficients'],
                                               float(np.max(np.abs(la['a'] - lb['a']) * xc.scale[None, :]) / max(1e-300, float(np.max(np.abs(la['a']) * xc.scale[None, :])))))
        r['covariance_rows'] = max(r['covariance_rows'], float(np.max(np.abs(la['psi2'] - lb['psi2'])) / max(1., float(np.max(np.abs(la['psi2']))))))
        if exact:
            r['covariance_effort'] = max(r['covariance_effort'], eff)
            r['covariance_margins'] = max(r['covariance_margins'], float(np.max(np.abs(la['margin'] - lb['margin'])) / max(1., float(np.max(la['margin'])))))
            r['covariance_storage'] = max(r['covariance_storage'], abs(la['storage'] - lb['storage']) / max(1., la['storage']))
        else:
            relaxed += 1
            r['covariance_effort_relaxed'] = max(r.get('covariance_effort_relaxed', 0.), eff)
        done += 1
    r['samples'] = samples
    r['covariance_relaxed_samples'] = relaxed
    return r


# ---------------------------------------------------------------------------------------------- independent plant
class PinPlant:
    """Pinocchio constrained dynamics of the variant graph with a fixed graph root and the declared actuator model.

    Rigid-body side (independent of the generated interfaces): the task coordinates of the joint-space partition are
    integrated (semi-implicit Euler), the dependent coordinates follow from Pinocchio's own closure residual by
    Newton's method and the tree velocity from the null space of its closure Jacobian; the model is built from the same
    compiled spanning tree and cut set, with Pinocchio's kinematics, inertia and constraint solver.  For a mechanism on
    declared ground contacts the anchors of the contacts are pinned by Pinocchio's point constraints (GroundedPinModel):
    they are dependent coordinates of this plant, and the multipliers of their constraints are its contact forces.
    Actuator side (the declared model, shared with the controller): channel-to-port map G, first-order force loops
    with the declared response times, effort bounds at the instantaneous port speed.  Added to it: a bias of the
    delivered efforts that changes in steps and keeps the one-step model error below 0.8 of the declared bound, and a
    piecewise-constant tool wrench of at most ``wrench_fraction`` of the declared floor in a random direction that
    changes every 1.5 s, so that also its jumps (at most twice the amplitude) stay inside the declared load bound."""

    def __init__(self, physical, xc, u0, dt, rng, error_fraction=0.8, wrench_fraction=0.45):
        self.xc, self.dt, self.rng = xc, dt, rng
        ci = xc.ci
        self.pm = pin_model(physical, xc, point_frames={'tool': (xc.tool_body, xc.tool_point)})
        ids = self.pm.tree_ids
        held = set(xc.held_ids)
        jspace = [k for k in physical['partition_requests']['joint_space'] if k not in held]      # commanded coordinates
        self.active = np.array([ids.index(k) for k in jspace])
        self.passive = np.array([i for i in range(len(ids)) if i not in self.active])
        self.E = np.zeros((len(ids), xc.nports))
        for c, jid in enumerate(ci.port_ids):
            self.E[ids.index(jid), c] = 1.
        self.port_idx = np.array([ids.index(k) for k in ci.port_ids])
        self.tree_idx = np.array([ids.index(k) for k in ci.tree_ids])
        self.u_idx = np.array([ids.index(k) for k in ci.independent_ids])
        self.task_idx = np.array([ids.index(k) for k in xc.task.ids])
        self.frames = [self.pm.body_frame[name] for name in xc.plan.frame_ids]
        self.tool = self.pm.point_frames['tool']
        cij = ci if xc.partition == 'joint_space' else CompiledInterface(physical, 'joint_space')
        full = np.asarray(cij.seed, float)[cij.active].copy()          # held coordinates at their seed values
        full[[cij.independent_ids.index(k) for k in jspace]] = np.asarray(u0, float)
        q_aug = closed_configuration(cij, full)
        self.q = np.array([q_aug[cij.coordinate_ids.index(k)] for k in ids])
        self.contact_force = None                            # forces of the ground on the contacts (n, 3), mechanisms on contacts
        self.v = np.zeros(len(ids))
        self.f = np.zeros(xc.m)                              # force-loop states (model part of the delivered efforts)
        self.bias = np.zeros(xc.m)
        self.error_fraction, self.wrench_fraction = error_fraction, wrench_fraction
        self.wrench = np.zeros(6)
        self.closure_max, self.t = 0., 0.
        self._next_bias = self._next_wrench = 0.
        self.project(self.q[self.active])

    def _factor(self):
        """Closure Jacobian of the present configuration and the pseudo-inverse of its passive block."""
        self._J = self.pm.closure_jacobian(self.q)
        self._Pinv = np.linalg.pinv(self._J[:, self.passive])

    def project(self, u):
        """Dependent coordinates for the commanded ones: Newton iteration on Pinocchio's closure residual with the closure
        Jacobian of the last accepted configuration (one step back), refreshed if the iteration is slow; the Jacobian of
        the accepted configuration is then formed once (it gives the tree velocity and serves the next call)."""
        self.q[self.active] = u
        if getattr(self, '_Pinv', None) is None:
            self._factor()
        for it in range(40):
            r = self.pm.closure_residual(self.q)
            if np.max(np.abs(r)) < 1e-12:
                break
            if it and it % 6 == 0:
                self._factor()
            self.q[self.passive] -= self._Pinv @ r
        self._factor()
        res = float(np.max(np.abs(self.pm.closure_residual(self.q))))
        if not res < 1e-8:
            raise RuntimeError(f'closure of the independent plant not reached (residual {res:.2e})')
        self.closure_max = max(self.closure_max, res)

    def set_velocity(self, ud):
        """Tree velocity in the null space of the closure Jacobian of the present (projected) configuration."""
        self.v[self.active] = ud
        self.v[self.passive] = -self._Pinv @ (self._J[:, self.active] @ ud)

    def poses(self):
        pin.forwardKinematics(self.pm.model, self.pm.data, self.q)
        pin.updateFramePlacements(self.pm.model, self.pm.data)
        oMf = self.pm.data.oMf
        return np.array([oMf[f].rotation for f in self.frames]), np.array([oMf[f].translation for f in self.frames])

    def delivered(self):
        return self.f + self.bias

    def measured_ports(self):
        return self.xc.G @ self.delivered()

    def external_tree_force(self):
        """Generalized force of the tool wrench on the tree coordinates of the controller graph (the true external load)."""
        Jt = pin.computeFrameJacobian(self.pm.model, self.pm.data, self.q, self.tool, pin.ReferenceFrame.LOCAL_WORLD_ALIGNED)
        return (Jt.T @ self.wrench)[self.tree_idx]

    def contact_forces_now(self):
        """Forces of the anchor constraints at the present state for the present delivered efforts and tool wrench."""
        Jt = pin.computeFrameJacobian(self.pm.model, self.pm.data, self.q, self.tool, pin.ReferenceFrame.LOCAL_WORLD_ALIGNED)
        self.pm.constrained_acceleration(self.q, self.v, self.E @ (self.xc.G @ self.delivered()) + Jt.T @ self.wrench)
        return self.pm.contact_forces()

    def step(self, phi):
        xc, dt = self.xc, self.dt
        if self.t >= self._next_bias:                         # force-loop error: bounded steps inside the declared bound
            e = xc.e_force
            self.bias = np.clip(self.bias + self.rng.uniform(-0.5, 0.5, xc.m) * e, -self.error_fraction * e, self.error_fraction * e)
            self._next_bias += 0.2
        if self.t >= self._next_wrench:                       # unknown tool wrench inside the declared floor
            d1, d2 = self.rng.standard_normal(3), self.rng.standard_normal(3)
            self.wrench = self.wrench_fraction * np.r_[xc.Wf * d1 / np.linalg.norm(d1), xc.Wm * d2 / np.linalg.norm(d2)]
            self._next_wrench += 1.5
        lo, hi = xc.bounds(self.v[self.port_idx])
        cmd = np.clip(phi, lo, hi)
        for j in range(xc.m):
            tau = xc.tau_act[j]
            self.f[j] = cmd[j] if tau <= 0. else cmd[j] + (self.f[j] - cmd[j]) * np.exp(-dt / tau)
        Jt = pin.computeFrameJacobian(self.pm.model, self.pm.data, self.q, self.tool, pin.ReferenceFrame.LOCAL_WORLD_ALIGNED)
        tau_tree = self.E @ (xc.G @ self.delivered()) + Jt.T @ self.wrench
        a = self.pm.constrained_acceleration(self.q, self.v, tau_tree)
        if xc.support is not None:
            self.contact_force = self.pm.contact_forces()
        ud = self.v[self.active] + dt * a[self.active]
        self.project(self.q[self.active] + dt * ud)
        self.set_velocity(ud)
        self.t += dt


def stroke_scenario(machine, physical, xc, overshoot=0.035, shadow=0.02):
    """Joint references that drive every cylinder beyond its stroke ends (one joint at a time from the test pose) and the
    joints beyond their declared limits.

    An end is commanded if a joint angle inside the assembly range reaches it (continuation from the test pose) and no
    other declared limit lies before it: at the target, no other pair may be violated by more than ``shadow`` beyond the
    overshoot.  Returns the timeline, the limits whose references were commanded, the ends that were not (with the
    reason) and the test pose."""
    ctrl_phys = physical
    xj = xc if xc.partition == 'joint_space' else compile_extended(physical, xc.spec, 'joint_space')
    planner = Planner(ctrl_phys, xj, machine)
    cij = planner.ci
    ids = list(planner.task_ids)                                 # commanded coordinates
    mid = np.array([xc.study['mid'][k] for k in ids], float)
    cylinders = physical['machine']['cylinders']
    twin = {}                                                    # cylinders of one channel move together
    for group in physical['actuator_groups'].values():
        for a in group:
            twin[a] = set(group)
    rows_at = lambda u: _pair_values(xj, planner, u)
    phases, exercised, skipped = [Segment('hold', 1.0, mid)], [], []
    seen = set()
    for cyl, c in cylinders.items():
        if cyl not in cij.coordinate_ids or cyl in seen:
            continue
        seen |= twin.get(cyl, {cyl})
        joint = c['joint']
        if joint not in ids:
            continue
        for end, target in (('extended', c['upper_m'] + overshoot), ('closed', c['lower_m'] - overshoot)):
            label = f'{cyl}:{end}'
            try:
                ang = planner.joint_for_coordinate(mid, joint, cyl, target, step=0.04, count=45)     # within 1.8 rad of the test pose
            except ValueError:
                skipped.append(dict(limit=label, reason='not reachable from the test pose'))
                continue
            goal = mid.copy()
            goal[ids.index(joint)] = ang
            vals = rows_at(goal)
            own = twin.get(cyl, {cyl})
            before = {pid: h for pid, h in vals.items() if pid not in own and h < -(overshoot + shadow)}
            if before:
                first = min(before, key=before.get)
                skipped.append(dict(limit=label, reason=f'preceded by {first} (h = {before[first]:+.3f} at the target)'))
                continue
            name = f"{c['kind']} {cyl} {end}"
            phases += [_paced(planner, xj, f'{name}: go', mid, goal), Segment(f'{name}: hold', 1.5, goal), _paced(planner, xj, f'{name}: back', goal, mid)]
            exercised.append(label)
    for label, joint, angle in xc.study['targets']:           # declared joint limits: references beyond them
        if joint not in ids:
            continue
        goal = mid.copy()
        goal[ids.index(joint)] = angle
        phases += [_paced(planner, xj, f'{label}: go', mid, goal), Segment(f'{label}: hold', 1.5, goal), _paced(planner, xj, f'{label}: back', goal, mid)]
        exercised.append(label)
    phases.append(Segment('hold end', 1.0, mid))
    return Timeline(phases), exercised, skipped, mid


def _pair_values(xc, planner, u):
    """Smallest safety function of every pair at the closed configuration of task coordinates u (fixed root)."""
    ci = planner.ci
    q = planner.closed(u)
    kin = xc.plan.evaluate(q[ci.tree_rows], np.zeros(ci.nt), dynamics=False)
    h = xc.barriers.values(kin.R, kin.p, q[ci.tree_rows])
    return {pid: float(np.min(h[idx])) for pid, idx in xc.barriers.pair_rows.items()}


def _paced(planner, xc, name, u0, u1, minimum=1.5, allowance=0.9):
    """Quintic segment whose port speeds stay inside the declared capabilities (targets may be inadmissible)."""
    ci = planner.ci
    u0, u1 = np.asarray(u0, float), np.asarray(u1, float)
    rows = [ci.coordinate_ids.index(p) for p in xc.ci.port_ids]
    worst = 0.
    for sfrac in np.linspace(0., 1., 11):
        try:
            q = planner.closed(u0 + sfrac * (u1 - u0))
        except ValueError:
            continue
        E, _ = ci.pacdm.mapping(q)
        v = E[rows][:, planner.free] @ (u1 - u0)
        worst = max(worst, float(np.max(np.where(v >= 0., v / xc.port_speed_hi, v / xc.port_speed_lo))) / allowance)
    return Segment(name, float(np.ceil(max(minimum, 1.875 * worst) * 10.) / 10.), u0, u1)


def closed_loop_run(machine, physical, xc, rng, duration=None, dt=0.001):
    timeline, exercised, skipped, u0 = stroke_scenario(machine, physical, xc)
    plant = PinPlant(physical, xc, u0, dt, rng)
    ctl = SafeVDC(xc, FilterOptions())
    monitor = RowMonitor(xc, dt)
    base = dict(position=np.zeros(3), rotation=np.eye(3), velocity=np.zeros(6), acceleration=np.zeros(6))
    every = int(round(xc.Ts / dt))
    total = int(round((duration or timeline.duration) / dt))
    keep = {k: [] for k in ('t', 'x', 'x_des', 'phi', 'phi_r', 'f', 'storage', 'n_active', 'feasible', 'hmin', 'load_error', 'load_bound')}
    start = time.perf_counter()
    phi = None
    engaged = np.zeros(len(xc.barriers.pair_ids), bool)      # pairs with a binding row in the effort filter or the required motion
    load_checks = load_violations = 0
    load_ratio_max = 0.
    sup = xc.support
    contact = None if sup is None else dict(normal_min=np.full(sup.n, np.inf), ratio_max=np.zeros(sup.n), model_error_max=0., row_steps=0,
                                            slack_max=0., samples=0)
    for step in range(total + 1):
        t = step * dt
        R, p = plant.poses()
        monitor.update_values(t, R, p, plant.q[plant.tree_idx])
        if phi is not None:
            # load assumption at the plant rate: true external load of this instant against the estimate of the last sample,
            # in the kinetic dual norm, against the declared bound of that sample
            Lk = ctl.last
            err = Lk['lift'].ET.T @ plant.external_tree_force() - Lk['tau_ext']
            err_norm = float(np.sqrt(max(err @ np.linalg.solve(Lk['Mr'], err), 0.)))
            load_checks += 1
            load_violations += int(err_norm > Lk['load_bound'] + 1e-9)
            load_ratio_max = max(load_ratio_max, err_norm / Lk['load_bound'])
        if step % every == 0:
            ref = timeline.references(t)
            u, ud = plant.q[plant.u_idx], plant.v[plant.u_idx]
            if phi is None:                                   # force loops start on the static holding efforts
                ctl.step(t, u, ud, base, np.zeros(xc.nports), ref)
                plant.f = ctl.last['phi_r'].copy()
                ctl.reset()
            phi = ctl.step(t, u, ud, base, plant.measured_ports(), ref)
            Lk = ctl.last
            if sup is not None:
                contact['row_steps'] += int(np.any(Lk['contact_active']))
                contact['slack_max'] = max(contact['slack_max'], float(np.max(Lk['contact_slack'], initial=0.)))
                # model at the measured efforts and the estimated load against the plant at the same state and efforts
                contact['model_error_max'] = max(contact['model_error_max'], float(np.max(np.abs(Lk['contact_force'] - plant.contact_forces_now()))))
                contact['samples'] += 1
            # pairs with a tight row (effort row at its right-hand side, or first-order row of the required motion at its
            # bound); tightness, unlike the sign of a multiplier, is the same for duplicate rows such as two boom cylinders
            tight = (Lk['c'] @ phi - Lk['rhs']) <= 1e-6 * (1. + np.abs(Lk['rhs']))
            bound_v = -Lk['rows'].alpha1[Lk['on']] * (Lk['h'] - Lk['sigma'])
            tight |= (Lk['hdot_r'] - bound_v) <= 1e-6 * (1. + np.abs(bound_v))
            engaged |= ctl._pair_mask(Lk['on'][tight])
            err = Lk['lift'].ET.T @ plant.external_tree_force() - Lk['tau_ext']
            for k, val in (('t', t), ('x', plant.q[plant.task_idx].copy()), ('x_des', np.array(ref[0])), ('phi', phi.copy()),
                           ('phi_r', Lk['phi_r'].copy()), ('f', plant.delivered()), ('storage', Lk['storage']),
                           ('n_active', int(np.sum(Lk['active']))), ('feasible', bool(Lk['feasible'])),
                           ('hmin', float(np.min(Lk['h'])) if len(Lk['h']) else np.inf),
                           ('load_error', float(np.sqrt(max(err @ np.linalg.solve(Lk['Mr'], err), 0.)))), ('load_bound', Lk['load_bound'])):
                keep[k].append(val)
        if step == total:
            break
        plant.step(phi)
        if sup is not None:
            F = plant.contact_force
            contact['normal_min'] = np.minimum(contact['normal_min'], F[:, 2])
            contact['ratio_max'] = np.maximum(contact['ratio_max'], np.linalg.norm(F[:, :2], axis=1) / np.maximum(F[:, 2], 1.))
    truth = monitor.summary()
    st = ctl.diagnostics()
    tr = {k: np.asarray(v) for k, v in keep.items()}
    e = tr['x'] - tr['x_des']
    pairs = truth['pairs']
    report = dict(
        duration_s=total * dt, wall_s=time.perf_counter() - start, commanded=exercised, not_commanded=skipped, phases=timeline.names,
        engaged_pairs=[pid for pid, on in zip(xc.barriers.pair_ids, engaged) if on],
        violated_pairs=[pid for pid, r in pairs.items() if r['h_min'] < 0.],
        classes=truth['classes'],
        stroke_h_min_m={pid: r['h_min'] for pid, r in pairs.items() if r['cls'] == 'stroke'},
        joint_h_min_rad={pid: r['h_min'] for pid, r in pairs.items() if r['cls'] == 'joint_limit'},
        infeasible_steps=int(st['qp_infeasible']), velocity_relaxed_steps=int(st['velocity_qp_relaxed']),
        intervention_fraction=float(np.mean(tr['n_active'] > 0)), storage_max_J=float(tr['storage'].max()),
        tracking_error_max_deg=np.rad2deg(np.abs(e).max(0)), tracking_error_max=np.abs(e).max(0), task_ids=list(xc.task.ids),
        contacts=None if sup is None else dict(
            ids=list(sup.ids), normal_force_min_N=contact['normal_min'], friction_ratio_max=contact['ratio_max'],
            declared_normal_force_min_N=[c['normal_min'] for c in sup.contacts], declared_friction=[c['friction'] for c in sup.contacts],
            model_error_max_N=contact['model_error_max'], model_error_samples=contact['samples'],
            contact_row_fraction=contact['row_steps'] / max(1, len(tr['t'])), contact_row_slack_max_N=contact['slack_max']),
        force_model_coverage=1. - st['force_model_violations'] / max(1, st['force_model_checks']),
        force_model_error_max_over_declared=st['force_model_error_max'] / xc.e_force,
        load_bound_coverage=1. - load_violations / max(1, load_checks), load_bound_checks=load_checks,
        load_error_max_over_bound=load_ratio_max,
        row_residual_coverage=None if st['row_residual_checks'] == 0 else 1. - st['row_residual_violations'] / st['row_residual_checks'],
        row_residual_checks=int(st['row_residual_checks']), late_activation_rows=int(st['late_activation_rows']),
        plant_closure_max_m=plant.closure_max, controller_mean_ms=1e3 * st['mean_wall_s'])
    return report, tr


def describe(xc, seconds):
    g = xc.manifest['graph']
    return dict(compile_s=seconds, bodies=g['bodies'], joints=g['joints'], tree_coordinates=g['tree_coordinates'], cuts=len(g['cuts']),
                cut_ids=g['cuts'], mobility=g['mobility'], commanded_mobility=g.get('commanded_mobility', g['mobility']),
                held_coordinates=len(g.get('held_ids', [])), contacts=0 if xc.support is None else xc.support.n,
                closure_rank=g['closure_rank'], modules=g['modules'],
                independent_ids=g['independent_ids'], body_modules=len(xc.plan.rigid_ids), barrier_rows=xc.barriers.R, study=xc.study,
                barrier_classes=xc.manifest['barriers']['classes'], ports=len(xc.ci.port_ids), channels=xc.m,
                port_speed_limits=np.c_[xc.port_speed_lo, xc.port_speed_hi], effort_scale=xc.scale, force_error=xc.e_force,
                theta=xc.theta, physical_sha256=xc.manifest['physical_sha256'][:16], spec_sha256=xc.manifest['spec_sha256'][:16])


def run(machine, *, only=None, samples=5, seed=3, duration=None, closed_loop=True, both_partitions=('baseline',)):
    out = machine.results_dir() / 'regeneration'
    out.mkdir(parents=True, exist_ok=True)
    for stale in list(out.glob('*.npz')) + [out / 'report.json']:      # a run that fails must not leave an older result in place
        stale.unlink(missing_ok=True)
    rng = np.random.default_rng(seed)
    sha = code_hash(machine.name)
    variants = machine.regeneration_variants(np.random.default_rng(5))
    names = [v[0] for v in variants if not only or v[0] in only]
    report = dict(status='RUNNING', machine=machine.name, expected_variants=names, variants={}, seed=seed, code_sha256=sha,
                  plant='Pinocchio ' + pin.__version__ + ' constrained dynamics of the variant graph, graph root fixed; actuator side: the '
                        'declared model (first-order force loops, effort bounds, channel map) with a bounded force bias and tool wrench')
    # machines whose independent plant is slow run the closed loop for the variants that the adapter names (all are audited)
    subset = getattr(machine, 'regeneration_closed_loop', None)
    report['closed_loop_variants'] = list(names if subset is None else [n for n in names if n in subset])
    for name, physical, change, text in variants:
        run_loop = closed_loop and (subset is None or name in subset)
        if only and name not in only:
            continue
        t0 = time.perf_counter()
        part = other_partition(physical)
        xc, cs = build(machine, physical, change, 'joint_space')
        xc_c, cs_c = build(machine, physical, change, part)
        rec = dict(description=text, other_partition=part, joint_space=describe(xc, cs), other=describe(xc_c, cs_c))
        box = test_box(machine, physical, Planner(physical, xc, machine))
        rec['audit'] = audit(physical, xc, xc_c, box, rng, samples, moving_root=not machine.ground_root)
        print(f"{name:22s} compiled in {cs * 1e3:5.1f} ms: {rec['joint_space']['bodies']} bodies, {rec['joint_space']['cuts']} cuts, mobility "
              f"{rec['joint_space']['mobility']} ({rec['joint_space']['commanded_mobility']} commanded), {rec['joint_space']['barrier_rows']} rows, "
              f"{rec['joint_space']['channels']} channels", flush=True)
        print('   audit:', {k: (f'{v:.1e}' if isinstance(v, float) else v) for k, v in rec['audit'].items()}, flush=True)
        if run_loop:
            parts = [('joint_space', xc)] + ([(part, xc_c)] if name in both_partitions else [])
            for partition, x in parts:
                rep, tr = closed_loop_run(machine, physical, x, np.random.default_rng(seed + 1), duration)
                rec[f'closed_loop_{partition}'] = rep
                np.savez_compressed(out / f'{name}__{partition}.npz', **tr, task_ids=np.array(x.task.ids), phase_names=np.array(rep['phases']))
                cl = rep['classes']
                print(f"   closed loop [{partition}] {rep['duration_s']:.0f} s (wall {rep['wall_s']:.0f} s): violated={rep['violated_pairs'] or 'none'} "
                      f"commanded={len(rep['commanded'])} engaged={rep['engaged_pairs']} not commanded={[s['limit'] for s in rep['not_commanded']]} "
                      f"infeasible={rep['infeasible_steps']}", flush=True)
                print('      h_min', {k: round(v['h_min'], 4) for k, v in cl.items()}, ' psi1_min', {k: round(v['psi1_min'], 4) for k, v in cl.items()})
                if rep.get('contacts'):
                    con = rep['contacts']
                    print('      contacts: normal min (kN)', np.round(np.asarray(con['normal_force_min_N']) / 1e3, 1), ' ratio max',
                          np.round(con['friction_ratio_max'], 2), ' model error max (N)', round(con['model_error_max_N'], 1),
                          ' contact rows active', round(con['contact_row_fraction'], 3))
                print('      psi2 min (plant rate)', {k: round(v['row_function_physics_rate_min'], 3) for k, v in cl.items()},
                      ' coverage force/load/row', round(rep['force_model_coverage'], 4), round(rep['load_bound_coverage'], 4), rep['row_residual_coverage'],
                      ' load error / bound max', round(rep['load_error_max_over_bound'], 3), flush=True)
            if len(parts) == 2:
                a = np.load(out / f'{name}__joint_space.npz')
                b = np.load(out / f'{name}__{part}.npz')
                n = min(len(a['t']), len(b['t']))
                rec['closed_loop_partition_difference'] = dict(task_coordinates_max_rad=float(np.max(np.abs(a['x'][:n] - b['x'][:n]))),
                                                               efforts_max_normalised=float(np.max(np.abs(a['phi'][:n] - b['phi'][:n]) / xc.scale)))
                print('      partition difference', rec['closed_loop_partition_difference'], flush=True)
        rec['wall_s'] = time.perf_counter() - t0
        report['variants'][name] = rec
        save_json(out / 'report.json', report)                    # status RUNNING until every variant is in
    report['status'] = 'COMPLETED'
    save_json(out / 'report.json', report)
    print('Saved', out / 'report.json')
    return report
