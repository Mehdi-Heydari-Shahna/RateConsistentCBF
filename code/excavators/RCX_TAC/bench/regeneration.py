"""Regeneration study of the extended RoboCompiler on one machine.

For every variant of the physical records (geometry, linkage, cylinder anchors, actuator arrangement, inertia, record
order, number of controlled degrees of freedom) and of the declared actuator capabilities, the control and safety
interfaces are regenerated by ``compile_extended`` from the changed inputs alone; no file of ``rcx/`` or ``core/``
differs between the variants.  Every regenerated interface is

  1. audited offline at random closed states: loop consistency of the required motion (velocity, acceleration and
     body-level compatibility at every cut joint), virtual-work assembly of the VDC modules against the reduced
     dynamics and against the affine map  M_r u_r_dot + N u_r + c0,  storage and dissipation identities, the rate of
     the reduced inertia against finite differences (skew-symmetry property), constrained accelerations against
     Pinocchio, barrier derivatives against finite differences, covariance of efforts, rows, margins and storage between
     the two declared partitions;
  2. run in closed loop on a plant with independent rigid-body dynamics: Pinocchio constrained dynamics of the *variant*
     graph (graph root fixed, no soil).  The actuator side of the plant is the declared model itself (channel map,
     first-order force loops, effort bounds at the instantaneous port speed) with a force-loop bias and an unknown
     tool wrench whose magnitudes are chosen inside their declared bounds.  The load bound and the force-loop model
     are monitored.  References drive every cylinder beyond its stroke ends, as far as an end can be reached from the
     test pose and is not preceded by another declared limit, and the joints beyond their declared limits, one of them
     declared on a loop-closing pin (a joint that the compiler cuts).

    python run.py <machine> regeneration
    python run.py <machine> regeneration --only baseline long_stick --no-closed-loop

A mechanism on declared ground contacts (specification section ``support``) is audited at rest of its root frame (the
ground); its Pinocchio model pins the frames of the contact anchors to the ground with Pinocchio's own point
constraints, so that the multipliers of these constraints are the contact forces of the plant: the generated
contact-force map is compared with them in the audit, and the closed-loop runs report the contact forces of the plant
(smallest normal force, largest ratio of tangential to normal force) next to those of the controller model.

The machine adapter supplies the variants (``regeneration_variants``) and the test pose with the declared limits of
the study (``regeneration_study``).  Outputs results/<machine>/regeneration/{report.json, <variant>__<partition>.npz}.
"""
