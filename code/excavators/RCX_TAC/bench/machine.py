"""Interface between a machine and the machine-independent bench.

A machine adapter supplies data only: the physical records of the controller graph and of the plant graph, the
control / safety / actuator specification for a site, the bucket section with its frame on the tool body, render and
support geometry of the plant bodies, the site layout, the hazard scenarios (references in task coordinates) and the
variants of the regeneration study.  No kinematic or dynamic expression of a mechanism is written in an adapter: those
are generated by the compiler (core/) and its extension (rcx/) from the records.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


class Machine:
    name = 'machine'
    title = 'machine'
    floating = True                      # the body fixed to the graph root frame carries a free joint in the plant
    hazard_scenarios = ('strokes', 'self', 'efence', 'dig_floor', 'dig_pipe')      # scenarios of the batch runs (batch.py)
    ablation_scenarios = ('dig_pipe', 'self')
    robustness_scenario = 'dig_pipe'
    # distance that references keep from the stroke ends of the cylinders (m): stroke margin of the safety specification
    # (zero of the stroke functions) plus a clearance larger than the static standoff of the filter, so that a nominal
    # reference does not rest inside the region where the stroke rows act
    stroke_reference_margin = 0.06
    # Records in machines/<name>/source may have separate licensing terms.
    source_separate = False

    # ------------------------------------------------------------------ records
    def physical(self, plant=False, **variant):
        raise NotImplementedError

    def spec(self, physical, **site):
        raise NotImplementedError

    def test_site(self):
        """Site keyword arguments of ``spec`` for the offline tests (all kinds of site elements)."""
        raise NotImplementedError

    def test_ranges(self, physical):
        """{task coordinate: (lower, upper)} of the random configurations of the offline tests, for coordinates without a
        declared window (default for those: -1.2 .. 1.2)."""
        return {}

    def joint_windows(self, physical):
        """Declared windows {joint id: (lower, upper)} that reference knots must respect in addition to the cylinder strokes."""
        return {}

    # ------------------------------------------------------------------ bucket
    def bucket_geometry(self):
        raise NotImplementedError

    def soil_frame(self):
        """(R_bs, p_bs): soil frame of the bucket (env.soil) in the frame of the tool body."""
        raise NotImplementedError

    # ------------------------------------------------------------------ plant scene
    def mesh_dir(self):
        return ROOT / 'machines' / self.name / 'source' / 'meshes'

    def asset_dir(self):
        return ROOT / 'results' / self.name / 'site_assets'

    def results_dir(self):
        return ROOT / 'results' / self.name

    def add_assets(self, asset):
        pass

    def add_geoms(self, body, elem, physical):
        pass

    def statistic(self):
        return ('3 3 1', '22')

    def base_drive(self, physical):
        """Record of the travel drive of the plant (rollers per side, radius, gauge, torque limit, servo gains) or None."""
        return None

    # ------------------------------------------------------------------ machines on ground contacts (whole-body graphs)
    ground_root = False                  # the root frame of the controller graph is the ground itself (not a moving base)
    support_friction = '1.0 .003 .008'   # friction of the level pad on which the machine stands (MuJoCo geom friction)
    # further attributes of the MuJoCo option element of the plant of this machine (default: none; a machine on contact
    # spheres declares the ratio of frictional to normal impedance of its contacts here)
    plant_option = {}

    def virtual_ids(self, physical):
        """Coordinates of the controller graph that are no joints of the plant (virtual chassis joints, contact anchors)."""
        return []

    def read_virtual(self, world, acceleration=False):
        """{id: (value, rate[, acceleration])} of the virtual coordinates from the plant state."""
        return {}

    def place_virtual(self, world, values):
        """Put the plant on the given values {id: value} of the virtual coordinates."""

    def virtual_frames(self, world):
        """{frame: (R, p)} of frames of the controller graph that are no bodies of the plant, from the plant state."""
        return {}

    def plant_com(self, world, payload=False):
        """Centre of mass of the bodies of the plant machine for the support rows of the truth monitor (the declared safety
        function is formed with the bodies of the graph); ``payload=True``: with the soil carried in the bucket."""
        return None

    def contact_truth(self, world):
        """Ground contacts of the plant: dict(normal (N), ratio (tangential / normal), slip (m), force (n, 3), depth (m; how
        far the contact body has sunk into the ground, optional)) per contact, or None for a machine without declared
        contacts."""
        return None

    # ------------------------------------------------------------------ documentation and report
    FOCUS = {}                           # pairs shown per scenario (and 'mission') in the report and the videos
    LABELS = {}                          # read-out text per pair

    def report_pairs(self):
        """Pairs listed in the mission table of the report."""
        out = []
        for pairs in self.FOCUS.values():
            out += [p for p in pairs if p not in out]
        return out

    def twin_groups(self):
        """Groups of pairs that move together (cylinders of one channel)."""
        return []

    def support_poses(self, planner):
        """[(label, task coordinates, payload in kg)] at which bench.facts evaluates the static support of the base."""
        return []

    def facts(self, physical, xc, planner):
        """Machine-specific computed findings for bench.facts (plain values)."""
        return {}

    def declarations(self, facts=None):
        """Lines of section 0 of the report: source of the records, changes, declared values and assumptions.  ``facts``:
        the record of bench.facts if it exists."""
        raise NotImplementedError

    def support_polygon(self, physical):
        """Convex support polygon of the base in the graph root frame (counter-clockwise, z = 0) or None.  Used by
        bench.stability for the static tipping margins of layouts and references; the plant itself is supported by contact."""
        return None

    # ------------------------------------------------------------------ helpers shared by adapters
    @staticmethod
    def to_body(T, p):
        """Point p (frame in which T is the body pose) in body coordinates."""
        T = np.asarray(T, float)
        return T[:3, :3].T @ (np.asarray(p, float) - T[:3, 3])

    @staticmethod
    def box_in_body(T, center, half):
        """Axis-aligned box given in the frame in which T is the body pose, as (center, half, rpy) in the body frame."""
        from scipy.spatial.transform import Rotation
        T = np.asarray(T, float)
        c = T[:3, :3].T @ (np.asarray(center, float) - T[:3, 3])
        import warnings
        with warnings.catch_warnings():                                    # a gimbal-locked decomposition is as valid as any other
            warnings.simplefilter('ignore')
            rpy = Rotation.from_matrix(T[:3, :3].T).as_euler('xyz')    # rotation body <- frame: R = Rz(y) Ry(p) Rx(r) with rpy_matrix
        return c.tolist(), [float(v) for v in half], [float(v) for v in rpy]
